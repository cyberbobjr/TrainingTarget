"""Project Viewpoint models of the Training Target tiles (optional sub-mod batman_TrainingTargetViewpoint).

    set PZ_FORGE=<path to pz-sprite-forge>      (the tile recipe imports it)
    blender -b --factory-startup -P source/viewpoint/export_viewpoint.py -- <project-root>

Builds every tile group of source/training_targets/build_training_targets.py (same geometry as the
sprites) and writes, under Contents/mods/batman_TrainingTargetViewpoint/common/media/training-viewpoint/:
  models/<group>.obj + .mtl   one model per group (base tiles and overlays)
  models/palette.png          flat colours, one 8 x 8 cell per paint of the recipe (next to the models,
                              like the texture of each Voxel Studio model)
  training.properties         Viewpoint manifest: model.<name>=<obj>, bind.<sprite>=<model>,<deg>,x,y,z,scale

Viewpoint model frame (read in its model pack format and in vanilla binds): Z up, 1 unit = 1 tile, origin at
the tile centre on the floor, south = +Y. The recipe builds with the front towards Blender -Y and the forge
camera looking from +X/-Y (east and south faces visible), so Blender -Y is south: the export mirrors Y and
reverses the winding. Facings S, E, N, W use the vanilla rotations 0, -90, 180, 90 degrees
(appliances_refrigeration_01_0..3 in the Voxel Studio pack). Overlays (attachedAnimSprite) are drawn by
Viewpoint only when they are bound too, so the impacts and the cans get their own models.
"""
import math
import os
import struct
import sys
import zlib
from pathlib import Path

import bpy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "training_targets"))
import build_training_targets as T  # noqa: E402

SUB_MOD = "batman_TrainingTargetViewpoint"
FOLDER = "training-viewpoint"
ROT = [0, -90, 180, 90]  # S, E, N, W
CELL, COLS = 8, 8

LIT = {}


def srgb(c):
    c = max(0.0, min(1.0, c))
    return int(round(255 * (12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055)))


def palette():
    keys = list(T.PAINTS)
    colours = {}
    for k in keys:
        colours[k] = LIT.get(k) or tuple(srgb(v) for v in T.PAINTS[k][1])
    rows = (len(keys) + COLS - 1) // COLS
    w, h = COLS * CELL, rows * CELL
    px = [[(255, 0, 255)] * w for _ in range(h)]
    uv = {}
    for i, k in enumerate(keys):
        cx, cy = (i % COLS) * CELL, (i // COLS) * CELL
        for y in range(cy, cy + CELL):
            for x in range(cx, cx + CELL):
                px[y][x] = colours[k]
        uv[k] = ((cx + CELL / 2) / w, 1 - (cy + CELL / 2) / h)
    return px, uv


def write_png(path, px):
    h, w = len(px), len(px[0])
    raw = b"".join(b"\x00" + bytes(c for p in row for c in p) for row in px)

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) \
        + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(data)


def descendants(objs):
    out, stack = [], list(objs)
    while stack:
        o = stack.pop()
        out.append(o)
        stack.extend(o.children)
    return out


def write_obj(path, objects, uv):
    dg = bpy.context.evaluated_depsgraph_get()
    lines = ["# Training Target model for Project Viewpoint (generated by source/viewpoint/export_viewpoint.py)",
             "# Z up, tile units, origin at the tile centre, south = +Y",
             f"mtllib {path.stem}.mtl", "usemtl palette"]
    vts, vt_index = [], {}
    v_lines, vn_lines, f_lines = [], [], []
    nv = nn = 0
    tris = 0
    for obj in objects:
        if obj.type != "MESH":
            continue
        ev = obj.evaluated_get(dg)
        me = ev.to_mesh()
        me.calc_loop_triangles()
        mw = obj.matrix_world
        nmat = mw.to_3x3().inverted_safe().transposed()
        base = nv
        for v in me.vertices:
            p = mw @ v.co
            v_lines.append(f"v {p.x:.5f} {-p.y:.5f} {p.z:.5f}")
            nv += 1
        mats = [m.name.split("tt_vp_", 1)[-1] if m else "pine" for m in me.materials]
        for tri in me.loop_triangles:
            key = mats[tri.material_index] if tri.material_index < len(mats) else "pine"
            if key not in vt_index:
                vt_index[key] = len(vts) + 1
                vts.append(uv.get(key, uv["pine"]))
            n = (nmat @ tri.normal).normalized()
            vn_lines.append(f"vn {n.x:.4f} {-n.y:.4f} {n.z:.4f}")
            nn += 1
            a, b, c = (base + i + 1 for i in tri.vertices)
            t = vt_index[key]
            # Mirrored Y: reverse the winding so the faces stay outward.
            f_lines.append(f"f {a}/{t}/{nn} {c}/{t}/{nn} {b}/{t}/{nn}")
            tris += 1
        ev.to_mesh_clear()
    lines += v_lines + [f"vt {u:.6f} {v:.6f}" for u, v in vts] + vn_lines + f_lines
    path.write_text("\n".join(lines) + "\n", encoding="ascii")
    path.with_suffix(".mtl").write_text("newmtl palette\nKd 1 1 1\nd 1\nmap_Kd palette.png\n", encoding="ascii")
    return tris


def main():
    project = Path(sys.argv[sys.argv.index("--") + 1] if "--" in sys.argv else ".").resolve()
    out = project / "Contents" / "mods" / SUB_MOD / "common" / "media" / FOLDER
    (out / "models").mkdir(parents=True, exist_ok=True)
    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    mats = {}
    for key in T.PAINTS:
        m = bpy.data.materials.new(f"tt_vp_{key}")
        mats[key] = m
    px, uv = palette()
    write_png(out / "models" / "palette.png", px)

    manifest = ["id=batman-training-target-viewpoint", "name=Training Target", "version=1"]
    report = []
    for group in T.tile_groups():
        root = bpy.data.objects.new("LW_VP_root", None)
        bpy.context.scene.collection.objects.link(root)
        parts = group["build"](T.Kit(root, mats)) or []
        if group["overlay"]:
            objects = descendants([getattr(p, "anchor", p) for p in parts])
        else:
            objects = descendants(root.children)
        bpy.context.view_layer.update()
        name = group["key"]
        tris = write_obj(out / "models" / f"{name}.obj", objects, uv)
        manifest.append(f"model.training-{name}=models/{name}.obj")
        for facing, index in enumerate(group["indices"]):
            manifest.append(f"bind.{T.SHEET}_{index}=training-{name},{ROT[facing]},0,0,0,1")
        report.append(f"{name}: {tris} triangles, sprites {group['indices']}")
        T.clear_subject(root)
        bpy.data.objects.remove(root, do_unlink=True)
    (out / "training.properties").write_text("\n".join(manifest) + "\n", encoding="ascii")
    print("\n".join(report))
    print(f"wrote {len(report)} models to {out}")


main()
